// ---------- Shared date range state ----------
let activeStart = "";
let activeEnd   = "";

function buildStatsQuery() {
    const params = new URLSearchParams();
    if (activeStart) params.set("start", activeStart);
    if (activeEnd)   params.set("end",   activeEnd);
    const qs = params.toString();
    return qs ? "/api/stats?" + qs : "/api/stats";
}

// ---------- Out-of-range banner helpers ----------
function showOutOfRangeBanner(anchorId, start, end) {
    const bannerId = anchorId + "-oor-banner";
    const existing = document.getElementById(bannerId);
    if (existing) existing.remove();

    const banner = document.createElement("div");
    banner.id = bannerId;
    banner.style.cssText = `
        background: linear-gradient(135deg, #fef3c7, #fde68a);
        border: 1px solid #f59e0b;
        border-radius: 12px;
        padding: 14px 20px;
        margin-bottom: 18px;
        font-size: 13px;
        color: #92400e;
        display: flex;
        align-items: center;
        gap: 10px;
    `;
    const rangeText = [start, end].filter(Boolean).join(" → ") || "selected range";
    banner.innerHTML = `
        <span style="font-size:18px;">🤖</span>
        <span>
            <b>No historical fire data for ${rangeText}.</b>
            Showing <b>ML-predicted</b> values generated by the Random Forest model for this date range.
            Use <b>7-Day Forecast</b> for weather-driven predictions.
        </span>
    `;
    const anchor = document.getElementById(anchorId);
    if (anchor) anchor.insertAdjacentElement("beforebegin", banner);
}

function removeBanner(anchorId) {
    const old = document.getElementById(anchorId + "-oor-banner");
    if (old) old.remove();
}

// ---------- Insights filter ----------
async function applyInsightsFilter() {
    const start = document.getElementById("ins-start").value;
    const end   = document.getElementById("ins-end").value;
    if (start && end && start > end) { alert("Start date must be before end date."); return; }
    activeStart = start;
    activeEnd   = end;
    const dsStart = document.getElementById("ds-start");
    const dsEnd   = document.getElementById("ds-end");
    if (dsStart) dsStart.value = start;
    if (dsEnd)   dsEnd.value   = end;
    updateFilterInfo("ins-filter-info", start, end);
    updateFilterInfo("ds-filter-info",  start, end);
    insightsLoaded = false;
    datasetsLoaded = false;
    loadInsights();
}

function resetInsightsFilter() {
    activeStart = ""; activeEnd = "";
    document.getElementById("ins-start").value = "";
    document.getElementById("ins-end").value   = "";
    const dsStart = document.getElementById("ds-start");
    const dsEnd   = document.getElementById("ds-end");
    if (dsStart) dsStart.value = "";
    if (dsEnd)   dsEnd.value   = "";
    updateFilterInfo("ins-filter-info", "", "");
    updateFilterInfo("ds-filter-info",  "", "");
    removeBanner("stats-grid");
    removeBanner("tbl-ds1");
    insightsLoaded = false;
    datasetsLoaded = false;
    loadInsights();
}

