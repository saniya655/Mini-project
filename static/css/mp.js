function mkChart(id, type, labels, datasets, options) {
    if (charts[id]) charts[id].destroy();
    charts[id] = new Chart(document.getElementById(id), { type, data: { labels, datasets }, options });
}

// ---------- Heatmap & ML Predict ----------
let map, heatLayer;

async function loadHeatmap(reset = false) {
    const data = await (await fetch("/api/heatmap")).json();
    if (!map) {
        map = L.map("map").setView(data.center, 4);
        L.tileLayer("https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png", {
            attribution: '© OpenStreetMap contributors'
        }).addTo(map);
    }
    if (heatLayer) map.removeLayer(heatLayer);
    const maxFrp = data.max_frp || 1;
    const points = data.points.map(([lat, lon, frp]) => [lat, lon, Math.min(1, frp / maxFrp)]);
    const fireGradient = { 0.4: '#ffffb2', 0.55: '#fecc5c', 0.7: '#fd8d3c', 0.85: '#f03b20', 1.0: '#bd0026' };
    heatLayer = L.heatLayer(points, { radius: 18, blur: 22, minOpacity: 0.6, gradient: fireGradient }).addTo(map);
    if (reset) document.getElementById("predict-result").textContent =
        "Showing: all historical fires (" + points.length + " sampled points)";
}

async function runPrediction() {
    const date = document.getElementById("predict-date").value;
    if (!date) { alert("Please pick a date first."); return; }
    document.getElementById("predict-result").textContent = "Running ML prediction...";
    const r = await fetch("/api/predict?date=" + date);
    const d = await r.json();
    if (d.error) { alert(d.error); return; }
    if (!map) await loadHeatmap();
    if (heatLayer) map.removeLayer(heatLayer);
    if (!d.points || d.points.length === 0) {
        document.getElementById("predict-result").textContent =
            "Model predicts no significant risk anywhere on " + date;
        return;
    }
    const points = d.points.map(([lat, lon, w]) => [lat, lon, w]);
    const fireGradient = { 0.4: '#ffffb2', 0.55: '#fecc5c', 0.7: '#fd8d3c', 0.85: '#f03b20', 1.0: '#bd0026' };
    heatLayer = L.heatLayer(points, { radius: 22, blur: 26, max: 1.0, minOpacity: 0.6, gradient: fireGradient }).addTo(map);
    document.getElementById("predict-result").innerHTML =
        `🤖 <b>ML Prediction</b> for <b>${d.date}</b> — ${points.length} risk zones identified`;
}

// ---------- Manual Predict ----------
async function runManualPredict() {
    const lat  = document.getElementById("m-lat").value;
    const lon  = document.getElementById("m-lon").value;
    const br   = document.getElementById("m-br").value;
    const bt31 = document.getElementById("m-bt31").value;
    const conf = document.getElementById("m-conf").value;
    const url  = `/api/manual_predict?lat=${lat}&lon=${lon}&brightness=${br}&bright_t31=${bt31}&confidence=${conf}`;
    const r    = await fetch(url);
    const d    = await r.json();
    const out  = document.getElementById("manual-result");
    out.style.display = "block";
    if (d.error) out.textContent = "Error: " + d.error;
    else out.innerHTML = `🔥 Predicted FRP: <span style="color:#b45309;">${d.predicted_frp} MW</span>`;
}

// ---------- 7-Day Forecast ----------
// Supports an optional start date — picks 7 days from that date onward.
// If no date is chosen, defaults to the next 7 days from today.
let forecastLoaded  = false;
let forecastStartDate = "";   // tracks the currently loaded start date

async function loadForecast() {
    // Always reload if the start date changed; skip only if nothing changed
    const pickedDate = (document.getElementById("forecast-start-date") || {}).value || "";
    if (forecastLoaded && pickedDate === forecastStartDate) return;

    forecastLoaded    = true;
    forecastStartDate = pickedDate;

    document.getElementById("forecast-body").innerHTML =
        "<tr><td colspan='8' class='loading'>⏳ Fetching weather data…</td></tr>";

    // Update table header
    const thead = document.querySelector("#forecast-table thead tr");
    if (thead) {
        thead.innerHTML = `
            <th>Date</th><th>Day</th><th>Predicted FRP (MW)</th>
            <th>Max Temp (°C)</th><th>Rain (mm)</th>
            <th>Wind (km/h)</th><th>Humidity (%)</th><th>Source</th>
        `;
    }

    // Update filter info label
    const filterInfo = document.getElementById("forecast-filter-info");
    if (filterInfo) {
        filterInfo.textContent = pickedDate
            ? `Showing 7 days from ${pickedDate}`
            : "Showing next 7 days from today";
    }

    const url  = pickedDate ? `/api/future?start=${pickedDate}` : "/api/future";
    const data = await (await fetch(url)).json();
    const tbody = document.getElementById("forecast-body");

    const frpValues = data.map(r => r.estimated_avg_frp);
    const minFRP    = Math.min(...frpValues);
    const maxFRP    = Math.max(...frpValues);

    function frpColor(val) {
        if (maxFRP === minFRP) return "#f59e0b";
        const ratio = (val - minFRP) / (maxFRP - minFRP);
        if (ratio < 0.33) return "#10b981";
        if (ratio < 0.66) return "#f59e0b";
        return "#f43f5e";
    }

    tbody.innerHTML = data.map(row => `
        <tr>
            <td>${row.date}</td>
            <td>${row.weekday || ""}</td>
            <td style="font-weight:700;color:${frpColor(row.estimated_avg_frp)}">${row.estimated_avg_frp}</td>
            <td>${row.temp_max !== null ? row.temp_max + " °C" : "—"}</td>
            <td>${row.precip   !== null ? row.precip   + " mm" : "—"}</td>
            <td>${row.wind     !== null ? row.wind     + " km/h" : "—"}</td>
            <td>${row.humidity !== null ? row.humidity + " %"  : "—"}</td>
            <td style="font-size:11px;color:#64748b">${row.source || ""}</td>
        </tr>
    `).join("");

    const labels = data.map(r => r.date + (r.weekday ? ` (${r.weekday})` : ""));
    const values = data.map(r => r.estimated_avg_frp);

    mkChart("forecast-chart", "line", labels, [{
        label: "Predicted FRP (MW)",
        data: values,
        borderColor: "#f59e0b",
        backgroundColor: "rgba(245,158,11,0.12)",
        borderDash: [6, 3],
        tension: 0.4,
        fill: true,
        pointStyle: "rectRot",
        pointRadius: 6,
        pointBackgroundColor: values.map(v => frpColor(v))
    }], {
        responsive: true,
        plugins: {
            legend: { display: false },
            tooltip: {
                callbacks: {
                    afterLabel: (ctx) => {
                        const row = data[ctx.dataIndex];
                        return row.temp_max !== null
                            ? [`🌡 ${row.temp_max}°C`, `🌧 ${row.precip}mm`,
                               `💨 ${row.wind}km/h`, `💧 ${row.humidity}%`]
                            : [];
                    }
                }
            }
        },
        scales: { x: { ticks: { maxRotation: 30 } } }
    });

    // Source badge
    let badge = document.getElementById("forecast-source-badge");
    if (!badge) {
        badge = document.createElement("div");
        badge.id = "forecast-source-badge";
        badge.style.cssText = "margin-top:10px;font-size:12px;font-weight:600;";
        const wrap = document.getElementById("forecast-body").closest(".forecast-table-wrap");
        if (wrap) wrap.after(badge);
    }
    const source = data[0]?.source || "";
    if (source.includes("Open-Meteo")) {
        badge.style.color = "#10b981";
        badge.textContent = "✅ Powered by Open-Meteo live weather + Random Forest ML model";
    } else {
        badge.style.color = "#f59e0b";
        badge.textContent = "⚠️ Weather API unavailable — using RF model with estimated weather inputs";
    }
}